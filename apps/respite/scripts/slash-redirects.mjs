// Permanent trailing-slash redirects for every built page.
//
// Cloudflare's static-asset layer answers /page with a 307 (temporary) to /page/. A temporary hop
// tells Google both URLs are live, so it indexes /page and /page/ side by side (seen in Search
// Console, Nov 2026). Rules in _redirects run before that layer and can say 301, so this adds one
// exact rule per page: "/page /page/ 301". Exact rules only (no splats), so /page/ itself never
// matches and nothing can loop. Cloudflare allows 2,000 static rules; the build fails well before.
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const LIMIT = 1800;
const SKIP_DIRS = new Set(["_worker.js", "_astro", "_server-islands"]);

/** Directories under dist that hold an index.html, as site paths without the trailing slash. */
export function pageDirs(distDir) {
	const out = [];
	const walk = (dir) => {
		for (const name of readdirSync(dir)) {
			if (SKIP_DIRS.has(name)) continue;
			const full = join(dir, name);
			if (!statSync(full).isDirectory()) continue;
			if (existsSync(join(full, "index.html"))) out.push("/" + relative(distDir, full).split(sep).join("/"));
			walk(full);
		}
	};
	walk(distDir);
	return out.sort();
}

/** The _redirects text with a 301 for each page that has no rule of its own yet. */
export function withSlashRules(existing, pages) {
	const taken = new Set(
		existing
			.split("\n")
			.map((l) => l.trim())
			.filter((l) => l && !l.startsWith("#"))
			.map((l) => l.split(/\s+/)[0]),
	);
	const rules = pages.filter((p) => !taken.has(p)).map((p) => `${p}  ${p}/  301`);
	const total = taken.size + rules.length;
	if (total > LIMIT) throw new Error(`_redirects would hold ${total} rules; Cloudflare's limit is 2,000`);
	if (!rules.length) return existing;
	return `${existing.replace(/\s*$/, "")}\n\n# Trailing slash: /page answers 301 to /page/ (generated by scripts/slash-redirects.mjs).\n${rules.join("\n")}\n`;
}

/** Astro integration: runs after the build, rewrites dist/_redirects. */
export default function slashRedirects() {
	return {
		name: "slash-redirects",
		hooks: {
			"astro:build:done": ({ dir, logger }) => {
				const distDir = fileURLToPath(dir);
				const file = join(distDir, "_redirects");
				const before = existsSync(file) ? readFileSync(file, "utf8") : "";
				const pages = pageDirs(distDir);
				const after = withSlashRules(before, pages);
				writeFileSync(file, after);
				const added = after.split("\n").length - before.split("\n").length;
				logger.info(`${pages.length} pages; _redirects now ends with their trailing-slash 301s (+${Math.max(0, added - 2)} rules)`);
			},
		},
	};
}
