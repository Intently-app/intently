// Permanent trailing-slash redirects for every built page.
//
// Cloudflare's static-asset layer answers /page with a 307 (temporary) to /page/. A temporary hop
// tells Google both URLs are live, so it indexes /page and /page/ side by side (seen in Search
// Console, Nov 2026). Rules in _redirects run before that layer and can say 301, so this adds one
// exact rule per page: "/page /page/ 301". Exact rules only (no splats), so /page/ itself never
// matches and nothing can loop. Cloudflare allows 2,000 static rules; the build fails well before.
//
// Cloudflare also matches each _redirects source exactly: a hand-written "/old /new/ 301" does not
// cover "/old/", which answers 404 (Search Console, Nov 2026: the hub sends liveintently.app/blog/x/
// here with the slash kept). So every hand-written exact rule gets a slashed twin with the same
// target, written right after it so it stays ahead of any splat (the first match wins).
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const LIMIT = 1800;
const SKIP_DIRS = new Set(["_worker.js", "_astro", "_server-islands"]);

/** Directories under dist that hold an index.html, as site paths without the trailing slash. */
export function pageDirs(distDir) {
	const out = [];
	const walk = (dir) => {
		for (const name of readdirSync(dir)) {
			if (SKIP_DIRS.has(name)) continue;
			const full = join(dir, name);
			if (!statSync(full).isDirectory()) continue;
			if (existsSync(join(full, "index.html"))) out.push("/" + relative(distDir, full).split(sep).join("/"));
			walk(full);
		}
	};
	walk(distDir);
	return out.sort();
}

/** A rule's source is an exact page path: no trailing slash, splat, :placeholder or file extension. */
export function twinnable(source) {
	if (!source.startsWith("/") || source === "/" || source.endsWith("/")) return false;
	if (source.includes("*") || source.includes(":")) return false;
	return !/\.[a-z0-9]+$/i.test(source.split("/").pop());
}

/**
 * The _redirects text with a slashed twin after each exact hand-written rule, then a 301 for each
 * page that has no rule of its own yet. A twin never shadows a built page (/x/ with an index.html).
 */
export function withSlashRules(existing, pages) {
	const sourceOf = (line) => {
		const t = line.trim();
		return t && !t.startsWith("#") ? t.split(/\s+/)[0] : null;
	};
	const lines = existing.split("\n");
	const taken = new Set(lines.map(sourceOf).filter(Boolean));
	const pageSet = new Set(pages);
	const out = [];
	let twins = 0;
	for (const line of lines) {
		out.push(line);
		const source = sourceOf(line);
		if (!source || !twinnable(source) || pageSet.has(source)) continue;
		const slashed = `${source}/`;
		if (taken.has(slashed)) continue;
		const [, target, status = ""] = line.trim().split(/\s+/);
		// "/a /a/ 301" written by hand: its twin would point at itself.
		if (!target || target.replace(/[?#].*$/, "") === slashed) continue;
		out.push(line.replace(line.trim(), [slashed, target, status].filter(Boolean).join("  ")));
		taken.add(slashed);
		twins++;
	}
	const rules = pages.filter((p) => !taken.has(p)).map((p) => `${p}  ${p}/  301`);
	const total = taken.size + rules.length;
	if (total > LIMIT) throw new Error(`_redirects would hold ${total} rules; Cloudflare's limit is 2,000`);
	const text = twins ? out.join("\n") : existing;
	if (!rules.length) return text;
	return `${text.replace(/\s*$/, "")}\n\n# Trailing slash: /page answers 301 to /page/ (generated by scripts/slash-redirects.mjs).\n${rules.join("\n")}\n`;
}

/** Astro integration: runs after the build, rewrites dist/_redirects. */
export default function slashRedirects() {
	return {
		name: "slash-redirects",
		hooks: {
			"astro:build:done": ({ dir, logger }) => {
				const distDir = fileURLToPath(dir);
				const file = join(distDir, "_redirects");
				const before = existsSync(file) ? readFileSync(file, "utf8") : "";
				const pages = pageDirs(distDir);
				const after = withSlashRules(before, pages);
				writeFileSync(file, after);
				const count = (t) => t.split("\n").filter((l) => l.trim() && !l.trim().startsWith("#")).length;
				logger.info(`${pages.length} pages; _redirects has ${count(after)} rules (+${count(after) - count(before)} slashed twins and trailing-slash 301s)`);
			},
		},
	};
}
